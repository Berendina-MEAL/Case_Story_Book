  summary: `Galahitiwela is a village within the Algoda Grama Niladhari Division of Dehiowita Divisional Secretariat, Kegalle District, roughly 1.5 kilometres from Dehiowita town. Algoda was selected as one of the target divisions for BDS project implementation in 2025, and many of the low-income families who live in Galahitiwela are among those the programme aims to reach.

To look after one another's welfare, the residents came together and formed the Ekamutu Subasadaka Sangamaya Saha Maranadara Samithiya, a society that today has about 101 members and was formally registered on 29 October 2025. Yet for all its strength in numbers, the society had nowhere to call its own. Monthly meetings were held in the home of one member, while the society's equipment was stored in another household. Every gathering depended on the goodwill of a family who gave up their living space, and the society's belongings were scattered rather than secure.

The community's answer was practical and generous. One member donated a plot of land to the society, and the members began building a hall themselves, completing the foundation and concrete pillars with money raised from member contributions and from selling the soil excavated while preparing the site. But the funds ran short of what a finished hall required. Having learned about the work of Berendina Development Services, the society's board approached BDS for support.

BDS responded from the budget allocated for community action projects, partnering with the society on a cost-sharing basis. BDS contributed LKR 346,741.75 of the LKR 835,241.75 total, while the society raised the remaining LKR 488,500.00 through member contributions and its own fundraising events, including a "Sal Pila" and a "Poson Zone". The community's contribution exceeded half of the project cost, a clear measure of how deeply the villagers wanted this hall and how far their own effort carried it.

Today the Galahitiwela Community Hall stands on the land donated by one of their own. It gives the society a permanent home for its meetings and equipment, and offers the wider community a shared space for gatherings, services, and learning, built through the dedication of its own members and strengthened by a timely partnership with BDS.`,

